def _remote_prompt(
    prompt: str,
    style: str,
    kind: str,
    *,
    size: tuple[int, int] | None = None,
    context: str = "",
) -> str:
    style_text = STYLE_PROMPTS.get(style, STYLE_PROMPTS["flat"])
    project = f" Project: {context.strip()}." if context and context.strip() else ""
    size_text = ""
    if size:
        size_text = f" Target output: {size[0]}x{size[1]} px."
    if kind == "background":
        return (
            f"Atmospheric 2D game background for a project.{project} Scene: {prompt}. "
            f"Wide composition, depth, layered foreground/midground/background, no characters, "
            f"no text, no watermark, no UI.{size_text} Premium indie game art, coherent lighting."
        )
    if kind == "icon":
        return (
            f"App icon for a program.{project} Symbol: {prompt}. Bold simple silhouette, centered, "
            f"premium dark navy and coral color palette, subtle glow, flat vector style, no text, "
            f"no letters, no watermark, square composition.{size_text}"
        )
    return (
        f"Single 2D game asset for a game or app.{project} Object: {prompt}. {style_text}."
        f"{size_text} One object only, centered, full subject visible, strong readable silhouette, "
        "harmonious saturated palette, professional game art, clean edges. Isolated on a solid "
        "pure magenta background (#FF00FF). No shadow on the background, no text, no watermark, "
        "no border, no extra objects."
    )


def _http_image(url: str, headers: dict[str, str] | None = None, timeout: int = 120) -> Image.Image:
    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": "ReasonableEngine/0.1 (image generation)",
            "Accept": "image/png,image/jpeg,image/webp,*/*",
            **(headers or {}),
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            data = response.read()
    except urllib.error.HTTPError as error:
        body = error.read().decode("utf-8", errors="replace")
        raise RuntimeError(_tr("The image server returned HTTP {code}: {body}", "Сервер изображений вернул HTTP {code}: {body}", code=error.code, body=body[:240])) from error
    except urllib.error.URLError as error:
        raise RuntimeError(_tr("No connection to the image server: {reason}", "Нет соединения с сервером изображений: {reason}", reason=error.reason)) from error
    except TimeoutError as error:
        raise RuntimeError(_tr("The image server did not respond in time.", "Сервер изображений не ответил вовремя.")) from error
    try:
        return Image.open(io.BytesIO(data))
    except Exception as error:
        raise RuntimeError(_tr("The server returned something that is not an image. Check the endpoint.", "Сервер вернул не изображение. Проверьте endpoint.")) from error


def _openai_image(prompt: str, config: dict[str, Any], *, size: tuple[int, int], kind: str) -> Image.Image:
    base = (config.get("base_url") or "").rstrip("/")
    if not base:
        raise RuntimeError(_tr("The image server Base URL is not set.", "Не задан Base URL сервера изображений."))
    if not base.endswith("/images/generations"):
        if base.endswith("/v1"):
            url = base + "/images/generations"
        else:
            url = base + "/v1/images/generations" if not base.endswith("/images/generations") else base
    else:
        url = base
    # Most OpenAI-compatible servers accept this subset.
    request_size = "1024x1024"
    payload = {
        "model": config.get("model") or "gpt-image-1",
        "prompt": prompt,
        "n": 1,
        "size": request_size,
    }
    if "gpt-image" not in payload["model"] and "dall-e" not in payload["model"]:
        payload["response_format"] = "b64_json"
    headers = {"Content-Type": "application/json", "Accept": "application/json"}
    if config.get("api_key"):
        headers["Authorization"] = f"Bearer {config['api_key']}"
    request = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers=headers, method="POST")
    try:
        with urllib.request.urlopen(request, timeout=180) as response:
            data = json.loads(response.read().decode("utf-8", errors="replace"))
    except urllib.error.HTTPError as error:
        body = error.read().decode("utf-8", errors="replace")
        raise RuntimeError(_tr("The image server returned HTTP {code}: {body}", "Сервер изображений вернул HTTP {code}: {body}", code=error.code, body=body[:240])) from error
    except urllib.error.URLError as error:
        raise RuntimeError(_tr("No connection to the image server: {reason}", "Нет соединения с сервером изображений: {reason}", reason=error.reason)) from error
    items = data.get("data") or []
    if not items:
        raise RuntimeError(_tr("The image server returned an empty response.", "Сервер изображений вернул пустой ответ."))
    item = items[0]
    if item.get("b64_json"):
        try:
            return Image.open(io.BytesIO(base64.b64decode(item["b64_json"])))
        except Exception as error:
            raise RuntimeError(_tr("Could not decode the base64 image.", "Не удалось декодировать base64 изображение.")) from error
    if item.get("url"):
        return _http_image(item["url"], headers={"Authorization": headers.get("Authorization", "")} if headers.get("Authorization") else None)
    raise RuntimeError(_tr("The image server response has no url or b64_json.", "В ответе сервера изображений нет url или b64_json."))


