def _ensure_output(path: Path) -> Path:
    if not path.is_absolute():
        path = Path.cwd() / path
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def generate_sprite(
    prompt: str,
    output_path: str | Path,
    *,
    style: str = "flat",
    size: int = 256,
    image_config: dict[str, Any] | None = None,
    seed: int | None = None,
    context: str = "",
) -> dict[str, Any]:
    prompt = prompt.strip()
    if not prompt:
        raise ValueError(_tr("The sprite prompt is empty.", "Пустой промпт для спрайта."))
    style = style if style in STYLE_PROMPTS else "flat"
    size = max(64, min(1024, int(size)))
    config = image_config or {}
    provider = str(config.get("provider") or "openai")
    if provider != "openai":
        raise RuntimeError(
            _tr(
                "No external image model is configured, so generate_sprite did not draw "
                "a template. Use the draw_sprite tool to compose the sprite from shapes "
                "or a pixel grid.",
                "Внешняя модель изображений не подключена, поэтому generate_sprite не стал "
                "подставлять шаблон. Используйте инструмент draw_sprite и нарисуйте спрайт "
                "фигурами или пиксельной сеткой.",
            )
        )
    output = _ensure_output(Path(output_path))
    seed_value = _stable_seed(prompt, style, seed)
    result = {
        "prompt": prompt,
        "style": style,
        "size": size,
        "seed": seed_value,
        "provider": provider,
        "fallback": False,
    }
    remote_prompt = _remote_prompt(prompt, style, "sprite", size=(size, size), context=context)
    try:
        image = _openai_image(remote_prompt, config, size=(size, size), kind="sprite")
        image = image.convert("RGBA")
        image = _chroma_key(image)
        image = _fit_canvas(image, size)
        image.save(output, "PNG")
    except Exception as exc:
        raise RuntimeError(
            _tr(
                "The image model could not generate the sprite: {error}. Use the draw_sprite "
                "tool to draw it directly, or fix the image provider settings.",
                "Модель изображений не смогла создать спрайт: {error}. Нарисуйте его через "
                "инструмент draw_sprite или исправьте настройки провайдера изображений.",
                error=str(exc)[:300],
            )
        ) from exc
    result.update(
        {
            "path": str(output),
            "message": _tr("The sprite was generated by the AI model.", "Спрайт сгенерирован ИИ-моделью."),
        }
    )
    return result


def generate_background(
    prompt: str,
    output_path: str | Path,
    *,
    width: int = 1280,
    height: int = 720,
    image_config: dict[str, Any] | None = None,
    seed: int | None = None,
    context: str = "",
    allow_fallback: bool = True,
) -> dict[str, Any]:
    prompt = prompt.strip() or "atmospheric fantasy landscape"
    width = max(320, min(1920, int(width)))
    height = max(240, min(1080, int(height)))
    output = _ensure_output(Path(output_path))
    config = image_config or {}
    seed_value = _stable_seed(prompt, "background", seed)
    result = {
        "prompt": prompt,
        "width": width,
        "height": height,
        "seed": seed_value,
        "provider": config.get("provider", "procedural"),
        "fallback": False,
    }
    provider = config.get("provider", "procedural")
    remote_error = None
    if provider == "openai":
        remote_prompt = _remote_prompt(prompt, "flat", "background", size=(width, height), context=context)
        try:
            image = _openai_image(remote_prompt, config, size=(width, height), kind="background")
            image = image.convert("RGB").resize((width, height), Image.Resampling.LANCZOS)
            image.save(output, "PNG")
            result.update({"path": str(output), "provider": provider, "message": _tr("The background was generated by the AI model.", "Фон сгенерирован ИИ-моделью.")})
            return result
        except Exception as exc:
            remote_error = str(exc)
            if not allow_fallback:
                raise
    image, meta = procedural_background(prompt, width=width, height=height, seed=seed_value)
    image.save(output, "PNG")
    result.update(
        {
            "path": str(output),
            "fallback": bool(remote_error) or provider == "procedural",
            "provider": "procedural",
            "message": (
                _tr("The offline background generator was used.", "Использован офлайн-генератор фонов.")
                if not remote_error
                else _tr("The image server is unavailable ({error}). The offline generator was used.", "Сервер изображений недоступен ({error}). Использован офлайн-генератор.", error=remote_error[:200])
            ),
            "procedural_meta": meta,
        }
    )
    return result


def generate_icon(
    prompt: str,
    output_path: str | Path,
    *,
    style: str = "icon",
    size: int = 512,
    image_config: dict[str, Any] | None = None,
    seed: int | None = None,
    context: str = "",
) -> dict[str, Any]:
    result = generate_sprite(
        prompt,
        output_path,
        style="icon",
        size=size,
        image_config=image_config,
        seed=seed,
        context=context,
    )
    return result
